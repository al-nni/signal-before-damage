def _foundation_section(R, st, W):
    """Раздел 3.4: Chronos-Bolt, два варианта входа, сравнение с факторной моделью и ансамблями."""
    from pdfkit import Paragraph as Pp
    g = RS.g
    s = R["summ"]
    avg = lambda m, h: float(s[(s.model == m) & (s.h == h)].MAE.mean())  # noqa: E731
    out = []
    fmj = R.get("foundation", {})
    out.append(Pp(
        "Chronos-Bolt (small, 48 млн параметров; Amazon, лицензия Apache-2.0) — предобученная модель для "
        "прогноза временных рядов. Мы применяем её без дообучения (zero-shot) на CPU и берём медиану "
        "прогноза. Подлинность весов проверена: SHA-256 файла model.safetensors совпадает с опубликованным "
        f"на huggingface.co/amazon/chronos-bolt-small{' ' if fmj.get('matches_published') else ' (не совпадает!) '}"
        "(src/sbd/foundation.py). Сравниваем два варианта входа: сырой лог-ряд МО и ряд отклонений МО от "
        "общего фактора. Во втором случае общая сезонность возвращается через сезонный шаг фактора, как в "
        "факторной модели.", st["body"]))
    hs = [1, 3, 6, 12]
    ms = ["prophet", "chronos_bolt_raw", "chronos_bolt", "factor_region", "ensemble", "ensemble_fm"]
    rows = [["Модель"] + [f"h = {h}" for h in (1, 3, 6, 12)] + ["6 категорий,<br/>h = 1"]]
    for m in ms:
        rows.append([MODEL_RU[m]] + [fmt(g(R, m, h)) for h in hs] + [fmt(avg(m, 1))])
    out.append(table(rows, st, [52 * mm] + [(W - 52 * mm) / 5] * 5, highlight_rows=(3, 6)))
    out.append(Pp("Таблица 1а. Фундаментальная модель: MAE, руб. на жителя в месяц. Столбцы h = 1…12 — "
                  "«Все категории»; последний столбец — среднее MAE по шести категориям на h = 1.", st["cap"]))
    raw1, rel1, fr1 = g(R, "chronos_bolt_raw", 1), g(R, "chronos_bolt", 1), g(R, "factor_region", 1)
    e1, efm1 = g(R, "ensemble", 1), g(R, "ensemble_fm", 1)
    better_fm = [h for h in hs if g(R, "ensemble_fm", h) < g(R, "ensemble", h)]
    out += bullets([
        f"На сыром ряду модель ошибается сильно: {fmt(raw1)} на h = 1 против {fmt(g(R, 'prophet', 1))} у "
        "Prophet, а на длинных горизонтах ещё больше. По 12–23 точкам одного МО она, как и Prophet, не может "
        "отделить сезонность от тренда.",
        f"На отклонениях от общего фактора та же модель — лучшая одиночная на горизонте 1 мес.: {fmt(rel1)} "
        f"против {fmt(fr1)} у «фактор + регион»; в среднем по шести категориям {fmt(avg('chronos_bolt', 1))} "
        f"против {fmt(avg('factor_region', 1))}. На горизонтах 3–12 мес. она немного уступает факторной модели "
        f"({fmt(g(R, 'chronos_bolt', 3))} против {fmt(g(R, 'factor_region', 3))} на h = 3).",
        f"Ансамбль с Chronos-Bolt (задан заранее, равные веса): {fmt(efm1)} на h = 1 против {fmt(e1)} у "
        "ансамбля без неё. " + (
            "Он точнее на всех горизонтах." if len(better_fm) == 4 else
            ("Он точнее на горизонтах " + ", ".join(str(h) for h in better_fm) + " мес. и уступает на остальных."
             if better_fm else "Точности он не добавляет.")),
        "Вывод: фундаментальная модель не заменяет перенос сезонности с панели, но хорошо дополняет его там, "
        "где нужно уловить местную динамику на ближайший месяц.",
    ], st)
    return out


def _long_h_note(R):
    """Где на длинных горизонтах Prophet оказался точнее (честная оговорка, строится из таблицы)."""
    worse = []
    for h in (6, 12):
        for c, v in RS.gain_cat(R, R["main"], h).items():
            if v < 0:
                worse.append((h, c, -v))
    if not worse:
        return "На всех горизонтах ансамбль лучше Prophet во всех категориях."
    parts = [f"{c.lower()} на h = {h} (+{fmt(v)}% к MAE)" for h, c, v in worse]
    return ("На длинных горизонтах Prophet местами точнее: " + ", ".join(parts) + ". Из первой точки прогноза "
            "(12.2023) сезонный шаг берётся из ряда по России, и модель не видит местного тренда — например, "
            "бурного роста маркетплейсов в 2024 году; h = 12 к тому же проверяется одной точкой.")


