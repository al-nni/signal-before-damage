def on_page(canvas, doc):
    canvas.saveState()
    canvas.setFont("Inter-Regular", 7.5)
    canvas.setFillColor(INK2)
    if doc.page > 1:
        canvas.drawString(18 * mm, 10 * mm, f"{TITLE} · {CONTEST}")
        canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, str(doc.page))
    canvas.restoreState()


